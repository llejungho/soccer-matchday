import { test } from 'node:test';
import assert from 'node:assert/strict';
import { DatabaseSync } from 'node:sqlite';
import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { initializeTeams, handleTeams } from '../teams.mjs';

test('tactics and custom ratings persist, isolate teams, delete scores and reset transferred evaluations', () => {
  const directory = mkdtempSync(path.join(tmpdir(), 'matchday-config-'));
  const filename = path.join(directory, 'test.sqlite');
  let db = new DatabaseSync(filename);
  const call = (route, input = {}, user = 1) => handleTeams(db, '/api/teams/' + route, { id: user }, input);
  const state = () => call('state').body;
  try {
    db.exec("CREATE TABLE users(id INTEGER PRIMARY KEY,email TEXT); INSERT INTO users VALUES(1,'a@example.com'),(2,'b@example.com');");
    initializeTeams(db);
    const teamId = call('create', {name:'A',color:'#123456'}).body.selectedTeam.id;
    const otherTeamId = call('create', {name:'B',color:'#123456'}).body.selectedTeam.id;
    call('select', {teamId}); call('players/add', {teamId,name:'선수'});
    const playerId = state().players[0].id;
    const tactic = {teamId,name:'전방압박',concept:'전방에서 압박',traits:'체력과 적극성이 높은 선수'};
    assert.equal(call('tactics/save', tactic).status, 200);
    const tacticId = state().tactics[0].id;
    assert.equal(call('tactics/save', {...tactic,tacticId,name:'킥 & 런',traits:'롱킥·헤딩이 좋은 선수'}).status, 200);
    assert.equal(call('tactics/save', {...tactic,name:''}).status, 400);
    assert.equal(call('tactics/save', {...tactic,traits:''}).status, 400);
    assert.equal(call('tactics/save', tactic, 2).status, 404);
    assert.equal(call('tactics/delete', {teamId:otherTeamId,tacticId}).status, 404);
    assert.equal(call('ratings/add', {teamId,name:'달리기 속도'}).status, 200);
    const fieldId = state().customFields[0].id;
    assert.equal(state().players[0].customRatings[fieldId], null);
    assert.equal(call('ratings/add', {teamId,name:'달리기 속도'}).status, 409);
    assert.equal(call('ratings/add', {teamId,name:'체력'}).status, 409);
    call('ratings/add', {teamId:otherTeamId,name:'멘탈'});
    call('select', {teamId:otherTeamId}); const otherFieldId = state().customFields[0].id;
    assert.deepEqual(state().tactics, []); call('select', {teamId});
    assert.equal(call('tactics/save', {...tactic,tacticId,traits:'',ratingFields:['stamina','custom:'+fieldId]}).status,200);
    assert.deepEqual(state().tactics[0].ratingFields,['stamina','custom:'+fieldId]);
    assert.equal(call('tactics/save', {...tactic,tacticId,ratingFields:['custom:'+otherFieldId]}).status,400);
    assert.equal(call('tactics/save', {...tactic,tacticId,ratingFields:['stamina','stamina']}).status,400);
    call('tactics/save', {...tactic,tacticId,name:'킥 & 런',traits:'롱킥·헤딩이 좋은 선수'});
    const profile = {teamId,playerId,name:'선수',positions:[],ratings:{stamina:null,aggression:null,attack:null,defense:null,overall:null},customRatings:{[fieldId]:5}};
    assert.equal(call('players/update', profile).status, 200);
    assert.equal(call('ratings/update', {teamId,fieldId,name:'스피드'}).status, 200);
    assert.equal(state().customFields[0].name, '스피드');
    assert.equal(state().players[0].customRatings[fieldId], 5);
    assert.equal(call('ratings/update', {teamId:otherTeamId,fieldId,name:'변경 불가'}).status, 404);
    assert.equal(call('ratings/update', {teamId,fieldId,name:'체력'}).status, 409);
    for (const score of [0,6,1.5,'5']) assert.equal(call('players/update', {...profile,customRatings:{[fieldId]:score}}).status, 400);
    assert.equal(call('players/update', {...profile,customRatings:{[otherFieldId]:5}}).status, 400);
    assert.equal(call('ratings/delete', {teamId:otherTeamId,fieldId}).status, 404);
    db.close(); db = new DatabaseSync(filename); initializeTeams(db);
    assert.equal(state().tactics[0].traits, '롱킥·헤딩이 좋은 선수');
    assert.equal(state().players[0].customRatings[fieldId], 5);
    call('players/update', {...profile,customRatings:{[fieldId]:null}});
    assert.equal(state().players[0].customRatings[fieldId], null);
    call('players/update', profile); call('ratings/delete', {teamId,fieldId});
    assert.equal(db.prepare('SELECT COUNT(*) AS count FROM player_custom_ratings').get().count, 0);
    assert.equal(call('players/update', profile).status, 400);
    call('ratings/add', {teamId,name:'헤딩'}); const newFieldId = state().customFields[0].id;
    assert.notEqual(newFieldId, fieldId);
    call('players/update', {...profile,customRatings:{[newFieldId]:4}});
    call('transfer/send', {teamId,email:'b@example.com'});
    const transferId = call('state',{},2).body.incoming[0].id;
    const accepted = call('transfer/respond', {transferId,decision:'accept'},2).body;
    assert.equal(accepted.tactics[0].id, tacticId);
    assert.equal(accepted.customFields[0].name, '헤딩');
    assert.equal(accepted.players[0].customRatings[newFieldId], null);
    assert.equal(call('tactics/delete', {teamId,tacticId}).status, 404);
    assert.equal(call('tactics/delete', {teamId,tacticId},2).status, 200);
    assert.equal(state().customFields[0].id, otherFieldId);
  } finally { db.close(); rmSync(directory,{recursive:true,force:true}); }
});
